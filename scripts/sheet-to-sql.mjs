// Turns your exported Google Sheet (File > Download > CSV) into SQL that imports the existing partners.
// Usage:  node scripts/sheet-to-sql.mjs partners.csv > import-partners.sql
// Then paste import-partners.sql into Supabase > SQL Editor > Run. Safe to run twice (existing emails/codes are skipped).
// Imported partners are NOT logged in yet: each one claims their row the first time they sign in with that email.
import { readFileSync } from "node:fs";

const file = process.argv[2];
if (!file) { console.error("Usage: node scripts/sheet-to-sql.mjs partners.csv > import-partners.sql"); process.exit(1); }

function parseCsv(t) {
  const rows = []; let row = [], cur = "", q = false;
  t = t.replace(/^﻿/, "");
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (q) { if (c === '"') { if (t[i + 1] === '"') { cur += '"'; i++; } else q = false; } else cur += c; }
    else if (c === '"') q = true;
    else if (c === ",") { row.push(cur); cur = ""; }
    else if (c === "\n" || c === "\r") { if (c === "\r" && t[i + 1] === "\n") i++; row.push(cur); cur = ""; if (row.some((x) => x !== "")) rows.push(row); row = []; }
    else cur += c;
  }
  row.push(cur); if (row.some((x) => x !== "")) rows.push(row);
  return rows;
}
const [head, ...data] = parseCsv(readFileSync(file, "utf8"));
const col = (name) => head.findIndex((h) => h.trim().toLowerCase() === name.toLowerCase());
const C = { first: col("First Name"), last: col("Last Name"), email: col("Email"), method: col("Select Payment Method"), bank: col("Bank Name"), accName: col("Account Name"), accNo: col("Account Number"), cname: col("Crypto Name"), net: col("Blockchain (Network)"), wallet: col("Wallet Address"), code: col("Generated Affiliate Code"), leads: col("Messages Received"), orders: col("Confirmed Orders"), clicks: col("Clicks") };
for (const k of ["first", "last", "email", "code"]) if (C[k] < 0) { console.error(`Column missing in CSV header: ${k}`); process.exit(1); }

// Sheet cells that start with ' (formula guard) or are "N/A" become empty.
const clean = (v) => { v = String(v ?? "").trim().replace(/^'/, ""); return /^n\/?a$/i.test(v) ? "" : v; };
const lit = (v) => (v === "" ? "null" : `'${v.replace(/'/g, "''").replace(/[\u0000-\u001f]/g, " ")}'`);
const num = (v) => { const n = parseInt(clean(v), 10); return Number.isFinite(n) && n >= 0 ? n : 0; };

const out = ["-- Generated by scripts/sheet-to-sql.mjs", "begin;"]; const seenE = new Set(), seenC = new Set(); let ok = 0; const skipped = [];
data.forEach((r, i) => {
  const g = (k) => (C[k] >= 0 ? clean(r[C[k]]) : "");
  const email = g("email").toLowerCase(), code = g("code").toUpperCase(), first = g("first").slice(0, 60), last = g("last").slice(0, 60);
  const why = !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) ? "bad email" : !/^[A-Z0-9]{3,16}$/.test(code) ? "bad code" : !first || !last ? "missing name" : seenE.has(email) ? "duplicate email" : seenC.has(code) ? "duplicate code" : "";
  if (why) { skipped.push(`row ${i + 2} (${email || "no email"}): ${why}`); return; }
  seenE.add(email); seenC.add(code); ok++;
  out.push(`insert into public.partners (email, first_name, last_name, code, clicks, leads, orders) values (${lit(email)}, ${lit(first)}, ${lit(last)}, ${lit(code)}, ${num(r[C.clicks])}, ${num(r[C.leads])}, ${num(r[C.orders])}) on conflict do nothing;`);
  const m = g("method").toLowerCase();
  if (m === "bank" || m === "crypto") out.push(`insert into public.partner_payouts (partner_id, method, bank_name, account_name, account_number, crypto_name, network, wallet_address) select id, '${m}', ${m === "bank" ? [lit(g("bank")), lit(g("accName")), lit(g("accNo")), "null", "null", "null"].join(", ") : ["null", "null", "null", lit(g("cname")), lit(g("net")), lit(g("wallet"))].join(", ")} from public.partners where code = ${lit(code)} on conflict do nothing;`);
});
out.push("commit;");
console.log(out.join("\n"));
console.error(`${ok} partner(s) ready.${skipped.length ? ` Skipped ${skipped.length}:\n  ` + skipped.join("\n  ") : ""}`);
